# Commented out IPython magic to ensure Python compatibility.
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# %matplotlib inline

df = pd.read_csv('/content/insurance.csv')

df.head()

df.shape

df.info()

df.describe(include='all')

df.drop_duplicates()

"""Data Analysis"""

x_axis = ['age', 'bmi', 'children', 'expenses']

for x in x_axis:
    fig, axes = plt.subplots(1, 2, figsize=(8, 3))

    # Histogram
    sns.histplot(df[x], ax=axes[0], kde=False, color='skyblue', bins=30)
    axes[0].set_title(f'Distribution of {x}')
    axes[0].grid(True)

    # Boxplot
    sns.boxplot(x=df[x], ax=axes[1], orient="h", showmeans=True, color='pink')
    axes[1].set_title(f'Boxplot of {x}')
    axes[1].grid(True)

    plt.tight_layout()
    plt.show()

"""Handle categorical columns"""

df.sex.unique()

df['sex'] = df.sex.map({'female': 0,'male':1})

df.smoker.unique()

df['smoker'] = df.smoker.map({'yes':1,'no': 0})

df['region'] = df.region.map({'southwest': 1,'southeast':2,'northwest':3 ,'northeast':4 })

df.head()

"""Split the dataset"""

x = df.drop(['expenses'],axis=1)

x.head()

y = df[['expenses']]

y.head()

from sklearn.model_selection import train_test_split

x_train, x_test, y_train, y_test = train_test_split(x,y,test_size=0.2,random_state=42)

x_train.shape

x_test.shape

"""Model Training

Random Forest Regressor
"""

from sklearn.ensemble import RandomForestRegressor

model = RandomForestRegressor()

model.fit(x_train, y_train)

y_pred = model.predict(x_test)

from sklearn.metrics import r2_score
score = r2_score(y_test,y_pred)
score

"""Predict charges in new customer"""

data = {
    'age': 40,
    'sex': 1,
    'bmi': 40,
    'children': 3,
    'smoker': 1,
    'region': 2
}

new_df = pd.DataFrame(data, index=[0])
new_df

pred = model.predict(new_df)
prediction = float(pred[0])
prediction = round(prediction, 2)
prediction

import joblib
joblib.dump(model, 'random_forest_regression')

import pickle

with open("insurance.pkl",'wb') as file:
  pickle.dump(model, file)

